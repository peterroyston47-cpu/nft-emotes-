function editionSizeForRarity(rarity: RarityTier): number {
  switch (rarity) {
    case 'Legendary':
      return 10;
    case 'Epic':
      return 25;
    case 'Rare':
      return 50;
    case 'Uncommon':
      return 100;
    case 'Common':
    default:
      return 250;
  }
}

// Character-specific subtle rig nuance so each character animates uniquely
function characterNuanceParams(
  base: ExpressionParams,
  characterId: CharacterId,
  index: number
): ExpressionParams {
  const waveOffset = ((index % 7) - 3) * 0.02;
  if (characterId === 'macaque') {
    return {
      ...base,
      browHeight: Math.max(-1, Math.min(1, base.browHeight + 0.04)),
      tempo: Number((base.tempo * 1.05).toFixed(2)),
    };
  }
  if (characterId === 'kitsune') {
    return {
      ...base,
      eyeOpenL: Math.max(0, Math.min(1.4, base.eyeOpenL - 0.05)),
      eyeOpenR: Math.max(0, Math.min(1.4, base.eyeOpenR - 0.05)),
      headTiltZ: Number((base.headTiltZ + waveOffset).toFixed(2)),
    };
  }
  if (characterId === 'tanuki') {
    return {
      ...base,
      cheekPuff: Math.min(1, base.cheekPuff + 0.12),
      blush: Math.min(1, base.blush + 0.08),
    };
  }
  return {
    ...base,
    pupilScale: Math.min(1.4, base.pupilScale + 0.08),
    tempo: Number((base.tempo * 0.96).toFixed(2)),
  };
}

export function buildInitialCatalog(): EmoteDesign[] {
  const catalog: EmoteDesign[] = [];

  for (const charId of CHARACTER_IDS) {
    const prefix =
      charId === 'macaque'
        ? 'MAC'
        : charId === 'kitsune'
          ? 'KIT'
          : charId === 'tanuki'
            ? 'TAN'
            : 'AXO';

    ARCHETYPES.forEach((arch, idx) => {
      const index = idx + 1;
      const code = `${prefix}-${String(index).padStart(3, '0')}`;
      const editionSize = editionSizeForRarity(arch.rarity);
      const mintedCount = Math.min(
        editionSize,
        Math.max(1, Math.floor(((index * 17 + charId.length * 13) % editionSize) * 0.82) + 1)
      );
      const priceMultiplier =
        charId === 'macaque' ? 1.15 : charId === 'kitsune' ? 1.05 : charId === 'axolotl' ? 1.0 : 0.95;
      const priceEth = Number((arch.basePrice * priceMultiplier + (index % 5) * 0.01).toFixed(2));
      const ownerIndex = (index + charId.charCodeAt(0)) % COLLECTOR_HANDLES.length;

      catalog.push({
        id: `${charId}-${index}`,
        code,
        index,
        characterId: charId,
        name: arch.charNames[charId],
        category: arch.category,
        description: arch.description,
        rarity: arch.rarity,
        priceEth,
        editionSize,
        mintedCount,
        platforms: arch.platforms,
        params: characterNuanceParams(arch.params, charId, index),
        creator: CREATOR_NAMES[charId],
        owner: COLLECTOR_HANDLES[ownerIndex],
        listedForSale: index % 4 !== 0, // 75% actively listed on marketplace
        likes: 42 + ((index * 19 + charId.charCodeAt(0) * 7) % 340),
      });
    });
  }

  return catalog;
}

